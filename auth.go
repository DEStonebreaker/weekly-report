package main

import (
	"bufio"
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"net/http"
	"net/url"
	"os"
	"path/filepath"
	"strings"

	"golang.org/x/oauth2"
	"golang.org/x/oauth2/google"
	gmailapi "google.golang.org/api/gmail/v1"
	tasksapi "google.golang.org/api/tasks/v1"
)

func loadOAuthConfig(credentialsPath string) (*oauth2.Config, error) {
	credentials, err := os.ReadFile(credentialsPath)
	if err != nil {
		return nil, fmt.Errorf("read client secret file: %w", err)
	}

	config, err := google.ConfigFromJSON(
		credentials,
		tasksapi.TasksReadonlyScope,
		gmailapi.GmailSendScope)
	if err != nil {
		return nil, fmt.Errorf("parse client secret file: %w", err)
	}

	return config, nil
}

func createGoogleClient(
	ctx context.Context,
	config *oauth2.Config,
	tokenPath string) (*http.Client, error) {

	token, err := loadToken(tokenPath)
	if err != nil {
		if !errors.Is(err, os.ErrNotExist) {
			return nil, err
		}

		token, err = authorizeWithGoogle(ctx, config)
		if err != nil {
			return nil, err
		}
		if err := saveTokenFile(tokenPath, token); err != nil {
			return nil, err
		}
	}

	return config.Client(ctx, token), nil
}

func loadToken(path string) (*oauth2.Token, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("read token file: %w", err)
	}

	var token oauth2.Token
	if err := json.Unmarshal(data, &token); err != nil {
		return nil, fmt.Errorf("unmarshal token file: %w", err)
	}

	return &token, nil
}

func saveTokenFile(path string, token *oauth2.Token) error {
	data, err := json.MarshalIndent(token, "", "  ")
	if err != nil {
		return fmt.Errorf("marshal token file: %w", err)
	}

	err = os.MkdirAll(filepath.Dir(path), 0700)
	if err != nil {
		return fmt.Errorf("create token file directory: %w", err)
	}

	err = os.WriteFile(path, data, 0600)
	if err != nil {
		return fmt.Errorf("write token file: %w", err)
	}

	err = os.Chmod(path, 0600)
	if err != nil {
		return fmt.Errorf("set token file permissions: %w", err)
	}

	return nil
}

func authorizeWithGoogle(
	ctx context.Context,
	config *oauth2.Config,
) (*oauth2.Token, error) {
	verifier := oauth2.GenerateVerifier() // Kept locally and secret until exchange for the key.
	state := oauth2.GenerateVerifier()

	authURL := config.AuthCodeURL(
		state,
		oauth2.AccessTypeOffline,
		oauth2.S256ChallengeOption(verifier))

	fmt.Println("Open this URL in your browser and approve access:")
	fmt.Println(authURL)
	fmt.Println()
	fmt.Println("After the localhost page fails, paste its complete URL here:")

	reader := bufio.NewReader(os.Stdin)
	input, err := reader.ReadString('\n')
	if err != nil {
		return nil, fmt.Errorf("read input: %w", err)
	}

	redirectURL, err := url.Parse(strings.TrimSpace(input))
	if err != nil {
		return nil, fmt.Errorf("parse OAuth redirect URL: %w", err)
	}

	query := redirectURL.Query()
	if oauthError := query.Get("error"); oauthError != "" {
		return nil, fmt.Errorf("Google authorization failed: %s", oauthError)
	}

	if query.Get("state") != state {
		return nil, fmt.Errorf("invalid OAuth state")
	}

	token, err := config.Exchange(
		ctx,
		query.Get("code"),               // Uniquely generated by Google
		oauth2.VerifierOption(verifier), // Proves possession over the verifier/code.
	)
	if err != nil {
		return nil, fmt.Errorf("exchange OAuth authorization code: %w", err)
	}

	return token, nil
}
